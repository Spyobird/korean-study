"""Merge research/lessons-*.json into data/curriculum.js. Run: python3 build.py"""
import glob, json, os, re, sys

POS = {"noun", "verb", "adjective", "adverb", "other"}
lessons, problems = {}, []
for path in sorted(glob.glob(os.path.join(os.path.dirname(__file__) or ".", "research", "lessons-*.json"))):
    for L in json.load(open(path, encoding="utf-8"))["lessons"]:
        n = int(L["n"])
        vocab = [{"ko": v["ko"].strip(), "en": v["en"].strip(), "pos": v.get("pos") if v.get("pos") in POS else "other"}
                 for v in L.get("vocab", []) if v.get("ko", "").strip() and v.get("en", "").strip()]
        grammar = [{"point": g["point"], "explanation": g.get("explanation", ""),
                    "examples": [e for e in g.get("examples", []) if e.get("ko", "").strip() and e.get("en", "").strip()]}
                   for g in L.get("grammar", []) if g.get("point")]
        if not vocab: problems.append(f"lesson {n}: no vocab")
        # Hangul only outside the Hangul tab: flag romanised Korean in Korean fields
        problems += [f"lesson {n}: Latin letters in Korean text: {k}" for k in [v["ko"] for v in vocab] +
                     [e["ko"] for g in grammar for e in g["examples"]] if re.search(r"[A-Za-z]", k)]
        if L.get("error"): problems.append(f"lesson {n}: {L['error']}")
        lessons[n] = {"n": n, "title": L.get("title", f"Lesson {n}"), "url": L.get("url", ""), "vocab": vocab, "grammar": grammar}

# Workbooks: AI-written practice per lesson, merged onto the lesson it belongs to
LATIN = re.compile(r"[A-Za-z]")
for path in sorted(glob.glob(os.path.join(os.path.dirname(__file__) or ".", "research", "workbook-*.json"))):
    for W in json.load(open(path, encoding="utf-8"))["lessons"]:
        n, ex, bad = int(W["n"]), [], []
        if n not in lessons: problems.append(f"workbook {n}: no such lesson"); continue
        for e in W.get("exercises", []):
            t = e.get("type")
            if t == "fill":
                opts = e.get("options", [])
                ok = (e.get("ko", "").count("___") == 1 and e.get("answer") in opts and len(set(opts)) == len(opts) >= 2
                      and e.get("en") and not any(LATIN.search(k) for k in [e["ko"], *opts]))
            elif t == "translate":
                ok = bool(e.get("en") and e.get("ko")) and not LATIN.search(e["ko"])
            else:
                ok = False
            (ex if ok else bad).append(e)
        problems += [f"workbook {n}: dropped bad exercise {json.dumps(e, ensure_ascii=False)}" for e in bad]
        r = W.get("reading")
        if r and (not r.get("ko") or LATIN.search(r["ko"]) or not all(q.get("q") and q.get("a") for q in r.get("questions", []))):
            problems.append(f"workbook {n}: dropped bad reading"); r = None
        lessons[n]["workbook"] = {"exercises": ex, "reading": r}

out = sorted(lessons.values(), key=lambda L: L["n"])
missing = sorted(set(range(0, max(lessons, default=0) + 1)) - set(lessons))
os.makedirs("data", exist_ok=True)
with open("data/curriculum.js", "w", encoding="utf-8") as f:
    f.write("// Generated by build.py from research/*.json — do not edit by hand.\n")
    f.write("const CURRICULUM = " + json.dumps({"lessons": out}, ensure_ascii=False) + ";\n")

print(f"{len(out)} lessons, {sum(len(L['vocab']) for L in out)} vocab, "
      f"{sum(len(g['examples']) for L in out for g in L['grammar'])} example sentences, "
      f"{sum(len(L.get('workbook', {}).get('exercises', [])) for L in out)} workbook exercises")
for p in problems + ([f"missing lessons: {missing}"] if missing else []):
    print("WARN", p, file=sys.stderr)
